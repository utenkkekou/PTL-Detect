#!/usr/bin/env python3
"""Add one completed T10 review batch to an existing clean4 dataset's train split.

The reviewed batch is bound by manifest/progress SHA256, must carry the frozen
independent-QA attestation, and is added only to train.  Base validation and
test files are copied or hard-linked unchanged so model comparisons remain
valid.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any

from PIL import Image

from ptl.constants import ATTESTATION_KEY as ATTESTATION
from ptl.constants import EXPECTED_NAMES

try:
    from scripts.build_shanghai_augmented_dataset import (
        _copy_base_dataset,
        _copy_or_link,
        _ordered_names,
        _validate_box,
        sha256_file,
    )
except ModuleNotFoundError:
    from build_shanghai_augmented_dataset import (  # type: ignore[no-redef]
        _copy_base_dataset,
        _copy_or_link,
        _ordered_names,
        _validate_box,
        sha256_file,
    )


def _expected_sha(value: str, label: str) -> str:
    normalized = value.strip().lower()
    if not re.fullmatch(r"[0-9a-f]{64}", normalized):
        raise ValueError(f"{label} must be exactly 64 hexadecimal characters")
    return normalized


def _dataset_yaml(output: Path) -> str:
    return "\n".join(
        [
            "# Generated by scripts/build_reviewed_train_augmentation.py",
            f"path: {output.resolve().as_posix()}",
            "train: images/train",
            "val: images/val",
            "test: images/test",
            "nc: 4",
            "names:",
            *[
                f"  {index}: {name}"
                for index, name in enumerate(EXPECTED_NAMES)
            ],
            "",
        ]
    )


def build_dataset(
    *,
    base: Path,
    frames_index_path: Path,
    manifest_path: Path,
    progress_path: Path,
    output: Path,
    expected_manifest_sha256: str,
    expected_progress_sha256: str,
    prefix: str,
    hardlink: bool = False,
) -> dict[str, Any]:
    if output.exists():
        raise FileExistsError(f"output already exists; refusing to overwrite: {output}")
    if _ordered_names(base / "data.yaml") != EXPECTED_NAMES:
        raise ValueError("base dataset does not use the clean4 four-class contract")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", prefix):
        raise ValueError("prefix may contain only ASCII letters, digits, _ and -")

    expected_manifest_sha256 = _expected_sha(
        expected_manifest_sha256, "expected_manifest_sha256"
    )
    expected_progress_sha256 = _expected_sha(
        expected_progress_sha256, "expected_progress_sha256"
    )
    actual_manifest_sha256 = sha256_file(manifest_path)
    actual_progress_sha256 = sha256_file(progress_path)
    if actual_manifest_sha256 != expected_manifest_sha256:
        raise ValueError(
            f"manifest SHA256 mismatch: {actual_manifest_sha256} != "
            f"{expected_manifest_sha256}"
        )
    if actual_progress_sha256 != expected_progress_sha256:
        raise ValueError(
            f"progress SHA256 mismatch: {actual_progress_sha256} != "
            f"{expected_progress_sha256}"
        )

    frames_index = json.loads(frames_index_path.read_text(encoding="utf-8"))
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    progress = json.loads(progress_path.read_text(encoding="utf-8"))
    if not isinstance(frames_index, list) or not isinstance(manifest, list):
        raise ValueError("frames index and manifest must be JSON arrays")
    if not isinstance(progress, dict):
        raise ValueError("progress must be a JSON object")

    ids = [str(item["id"]) for item in manifest]
    if len(ids) != len(set(ids)) or len(ids) != len({item.casefold() for item in ids}):
        raise ValueError("manifest contains duplicate IDs")
    indexed: dict[str, dict[str, Any]] = {}
    for record in frames_index:
        source = Path(str(record["path"]))
        item_id = source.stem
        if item_id in indexed:
            raise ValueError(f"duplicate frame index ID: {item_id}")
        indexed[item_id] = record
    if set(indexed) != set(ids):
        raise ValueError(
            f"frames/manifest ID mismatch: frames={len(indexed)}, manifest={len(ids)}"
        )
    if set(progress) != set(ids):
        raise ValueError(
            f"progress/manifest ID mismatch: progress={len(progress)}, manifest={len(ids)}"
        )

    reviewed_boxes: dict[str, list[tuple[int, float, float, float, float]]] = {}
    class_counts: Counter[int] = Counter()
    empty_images = 0
    source_records: dict[str, tuple[Path, str]] = {}
    source_hashes: set[str] = set()
    scenes: set[str] = set()
    for item in manifest:
        item_id = str(item["id"])
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", item_id):
            raise ValueError(f"unsafe manifest ID: {item_id!r}")
        saved = progress[item_id]
        if (
            saved.get("status") != "reviewed"
            or saved.get("attestation") != ATTESTATION
            or not str(saved.get("by", "")).strip()
            or not isinstance(saved.get("boxes"), list)
        ):
            raise ValueError(f"{item_id}: review is not frozen and independently attested")
        boxes = [
            _validate_box(item_id, index, box)
            for index, box in enumerate(saved["boxes"])
        ]
        if len(boxes) != len(set(boxes)):
            raise ValueError(f"{item_id}: exact duplicate reviewed boxes")
        reviewed_boxes[item_id] = boxes
        class_counts.update(box[0] for box in boxes)
        empty_images += not boxes

        record = indexed[item_id]
        source = Path(str(record["path"]))
        if not source.is_file():
            raise FileNotFoundError(f"{item_id}: indexed frame missing: {source}")
        if source.name != str(item["file"]):
            raise ValueError(f"{item_id}: indexed filename does not match manifest")
        with Image.open(source) as image:
            if image.size != (int(item["width"]), int(item["height"])):
                raise ValueError(f"{item_id}: source dimensions do not match manifest")
        source_hash = sha256_file(source)
        if source_hash in source_hashes:
            raise ValueError(f"{item_id}: exact duplicate within augmentation batch")
        source_hashes.add(source_hash)
        source_records[item_id] = (source, source_hash)
        scene = str(record.get("location", "")).strip()
        if not scene:
            raise ValueError(f"{item_id}: frame index has no scene/location")
        scenes.add(scene)

    output.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=f"{output.name}.tmp-", dir=output.parent))
    try:
        base_counts, base_hashes, used_train_stems = _copy_base_dataset(
            base, stage, hardlink
        )
        overlap = source_hashes & base_hashes
        if overlap:
            raise ValueError(
                f"augmentation has {len(overlap)} exact image duplicates with base"
            )

        for item in manifest:
            item_id = str(item["id"])
            source, _ = source_records[item_id]
            destination_stem = f"{prefix}__{item_id}"
            if destination_stem.casefold() in used_train_stems:
                raise ValueError(f"train destination stem collision: {destination_stem}")
            used_train_stems.add(destination_stem.casefold())
            destination_image = (
                stage / "images" / "train"
                / f"{destination_stem}{source.suffix.lower()}"
            )
            _copy_or_link(source, destination_image, hardlink)
            destination_label = (
                stage / "labels" / "train" / f"{destination_stem}.txt"
            )
            destination_label.parent.mkdir(parents=True, exist_ok=True)
            lines = [
                f"{cls} {cx:.6f} {cy:.6f} {width:.6f} {height:.6f}"
                for cls, cx, cy, width, height in reviewed_boxes[item_id]
            ]
            destination_label.write_text(
                "\n".join(lines) + ("\n" if lines else ""),
                encoding="utf-8",
            )

        final_counts = dict(base_counts)
        final_counts["train"] += len(manifest)
        (stage / "data.yaml").write_text(_dataset_yaml(output), encoding="utf-8")
        report: dict[str, Any] = {
            "schema_version": 1,
            "builder": "scripts/build_reviewed_train_augmentation.py",
            "base_dataset": str(base.resolve()),
            "base_counts": base_counts,
            "final_counts": final_counts,
            "augmentation_split": "train",
            "augmentation_images": len(manifest),
            "augmentation_scenes": sorted(scenes),
            "augmentation_empty_images": empty_images,
            "augmentation_boxes": sum(class_counts.values()),
            "augmentation_class_counts": {
                EXPECTED_NAMES[index]: class_counts[index]
                for index in range(len(EXPECTED_NAMES))
            },
            "frames_index_sha256": sha256_file(frames_index_path),
            "manifest_sha256": actual_manifest_sha256,
            "progress_sha256": actual_progress_sha256,
            "review_attestation": ATTESTATION,
            "exact_sha_overlap_with_base": 0,
            "base_val_test_modified": False,
            "hardlinked": hardlink,
        }
        (stage / "augmentation_report.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        stage.replace(output)
        return report
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", required=True)
    parser.add_argument("--frames-index", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--progress", required=True)
    parser.add_argument("--expected-manifest-sha256", required=True)
    parser.add_argument("--expected-progress-sha256", required=True)
    parser.add_argument("--prefix", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--hardlink", action="store_true")
    args = parser.parse_args()
    report = build_dataset(
        base=Path(args.base),
        frames_index_path=Path(args.frames_index),
        manifest_path=Path(args.manifest),
        progress_path=Path(args.progress),
        output=Path(args.out),
        expected_manifest_sha256=args.expected_manifest_sha256,
        expected_progress_sha256=args.expected_progress_sha256,
        prefix=args.prefix,
        hardlink=args.hardlink,
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
